/* Fetches the snapshot behind the deck's citation-graph slide and writes it to
 * ../graph-data.js. Run from the repo root (node 18+, no dependencies):
 *
 *   node posts/how-to-read-a-paper-in-the-age-of-ai/src/fetch_citation_graph.js
 *
 * The pool is Keshav's "How to read a paper" (2007), the papers it cites, and
 * every paper Semantic Scholar lists as citing it, each with its own reference
 * list. Choosing which of them the slide draws is the model's job (graph.js),
 * so the selection can be re-read without fetching again.
 *
 * Each paper carries Semantic Scholar's own field-of-study tags (`f`), which is
 * how the slide shows where the citations come from.
 *
 * References are stored as integers: i < papers.length is that pool paper, and
 * a larger integer is some paper outside the pool. Identity is all the model
 * needs from them, to count shared references, and it keeps the file small.
 *
 * The API rate-limits unauthenticated callers hard, so every request retries
 * with a growing wait on HTTP 429. Re-running it on a later date gives a
 * different snapshot; the deck quotes the date it was taken.
 */
"use strict";
const fs = require("fs");
const path = require("path");

const API = "https://api.semanticscholar.org/graph/v1";
const SEED = "15bd289b853f97eab5a5e930bfc27f3f803ce81d"; // Keshav 2007
const OUT = path.join(__dirname, "..", "graph-data.js");

const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
async function call(url, body) {
  for (let i = 0; i < 12; i++) {
    const res = await fetch(url, body
      ? { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) }
      : {});
    if (res.status === 429) { await sleep(3000 + 2000 * i); continue; }
    if (!res.ok) throw new Error(`${res.status} ${url}`);
    return res.json();
  }
  throw new Error(`still rate-limited: ${url}`);
}

(async () => {
  const seed = await call(`${API}/paper/${SEED}?fields=title,year,citationCount,references.paperId`);
  const cited = (seed.references || []).map((r) => r.paperId).filter(Boolean);

  const citing = [];
  for (let offset = 0; ; offset += 1000) {
    const page = await call(`${API}/paper/${SEED}/citations?fields=paperId&limit=1000&offset=${offset}`);
    page.data.forEach((d) => d.citingPaper.paperId && citing.push(d.citingPaper.paperId));
    if (page.next === undefined) break;
  }

  const ids = [SEED, ...cited, ...citing.filter((id) => !cited.includes(id))];
  const rows = [];
  for (let i = 0; i < ids.length; i += 400) {
    rows.push(...await call(`${API}/paper/batch?fields=title,year,citationCount,s2FieldsOfStudy,references.paperId`,
      { ids: ids.slice(i, i + 400) }));
  }

  const index = new Map(ids.map((id, i) => [id, i]));
  const outside = new Map();
  const code = (id) => {
    if (index.has(id)) return index.get(id);
    if (!outside.has(id)) outside.set(id, ids.length + outside.size);
    return outside.get(id);
  };
  const papers = ids.map((id, i) => {
    const p = rows[i] || {};
    const refs = p.references ? p.references.map((r) => r.paperId).filter(Boolean).map(code) : [];
    return {
      id, t: p.title || "", y: p.year || null, c: p.citationCount || 0,
      f: [...new Set((p.s2FieldsOfStudy || []).map((x) => x.category))],
      k: i === 0 ? "seed" : i <= cited.length ? "cited" : "citing", r: refs
    };
  });

  const data = { fetched: new Date().toISOString().slice(0, 10), source: "Semantic Scholar Graph API", papers };
  fs.writeFileSync(OUT,
    "/* Generated by src/fetch_citation_graph.js -- do not edit by hand. Semantic Scholar\n" +
    " * data: Keshav's \"How to read a paper\" (2007), what it cites, and what cites it. */\n" +
    "\"use strict\";\nvar PaperGraphData = " + JSON.stringify(data) + ";\n" +
    "if (typeof module !== \"undefined\" && module.exports) module.exports = PaperGraphData;\n");
  const withRefs = papers.filter((p) => p.k === "citing" && p.r.length).length;
  console.log(`${papers.length} papers (${cited.length} cited by the seed, ${citing.length} citing it; ` +
    `${withRefs} citing papers came with a reference list) -> ${path.relative(process.cwd(), OUT)}`);
})().catch((e) => { console.error(e.message); process.exit(1); });
